import type { Plugin } from 'vite';
import { createHash } from 'node:crypto';

/**
 * Minimal offline support without a runtime dependency.
 *
 * At build time this plugin emits `sw.js` containing the list of every emitted
 * asset. The service worker precaches them on install (cache name is a content
 * hash, so a new build invalidates the old cache) and serves them cache-first.
 * Navigation requests fall back to the cached shell. Only same-origin GET
 * requests are ever handled; nothing is sent to third parties.
 */
export function forgeServiceWorker(): Plugin {
  return {
    name: 'forge-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => f !== 'sw.js');
      const extra = ['./', 'manifest.webmanifest', 'icon.svg'];
      const urls = Array.from(new Set([...extra, ...files])).sort();
      const hash = createHash('sha256').update(urls.join('|')).digest('hex').slice(0, 12);
      const hashes = files
        .map((f) => {
          const item = bundle[f];
          if (!item) return '';
          const body = item.type === 'asset' ? String(item.source) : item.code;
          return createHash('sha256').update(body).digest('hex').slice(0, 8);
        })
        .join('');
      const version = createHash('sha256').update(hash + hashes).digest('hex').slice(0, 12);
      const source = `/* Generated by scripts/sw-plugin.ts — do not edit. */
const CACHE = 'claude-forge-${version}';
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('claude-forge-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).catch(() => (req.mode === 'navigate' ? caches.match('./') : Response.error()));
    })
  );
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
