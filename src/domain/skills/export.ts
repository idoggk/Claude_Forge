import JSZip from 'jszip';
import type { SkillContent, LiveTest } from './model';
import { generateSkillMd, normalizeText } from './generate';
import { isValidSkillName, validateResourcePath } from './paths';
import { validateSkillContent, type Finding } from './validate';

export class ExportBlockedError extends Error {
  findings: Finding[];
  constructor(findings: Finding[]) {
    super(`Export blocked by ${findings.length} error(s): ${findings.map((f) => f.message).join(' | ')}`);
    this.name = 'ExportBlockedError';
    this.findings = findings;
  }
}

function assertWellFormed(label: string, text: string): void {
  const wf = (text as string & { isWellFormed?: () => boolean }).isWellFormed;
  const ok = typeof wf === 'function' ? wf.call(text) : !/[\uD800-\uDBFF](?![\uDC00-\uDFFF])|(?<![\uD800-\uDBFF])[\uDC00-\uDFFF]/.test(text);
  if (!ok) throw new Error(`${label} contains invalid Unicode (a lone surrogate) and cannot be encoded as UTF-8.`);
}

export interface SkillExport {
  blob: Blob;
  filename: string;
  /** Every file path inside the ZIP, relative to the archive root. */
  entries: string[];
  skillMd: string;
}

/**
 * Build an installable Skill directory as a ZIP: `<name>/SKILL.md` plus supporting files.
 * Nothing is executed or read from disk; contents come only from the draft.
 * The export is refused when validation reports errors.
 */
export async function buildSkillZip(content: SkillContent): Promise<SkillExport> {
  const { findings } = validateSkillContent(content);
  const errors = findings.filter((x) => x.severity === 'error');
  if (errors.length > 0) throw new ExportBlockedError(errors);

  const name = content.name.trim();
  if (!isValidSkillName(name)) throw new ExportBlockedError([{ id: 'name-format', severity: 'error', area: 'metadata', message: `Invalid Skill name "${name}".` }]);

  const skillMd = generateSkillMd(content);
  assertWellFormed('SKILL.md', skillMd);

  const zip = new JSZip();
  const fixedDate = new Date(Date.UTC(2026, 0, 1));
  const entries: string[] = [];
  const add = (relative: string, text: string) => {
    const full = `${name}/${relative}`;
    if (full.includes('..') || full.startsWith('/') || full.includes('\\')) throw new Error(`Unsafe path rejected: ${relative}`);
    zip.file(full, normalizeText(text), { date: fixedDate, createFolders: false, binary: false });
    entries.push(full);
  };
  add('SKILL.md', skillMd);
  for (const r of content.references) {
    const check = validateResourcePath(r.path);
    if (!check.ok) throw new Error(`Unsafe supporting-file path "${r.path}": ${check.reason}`);
    assertWellFormed(r.path, r.content);
    add(r.path, r.content);
  }
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE', compressionOptions: { level: 6 }, platform: 'UNIX' });
  return { blob, filename: `${name}.zip`, entries, skillMd };
}

/** A separate Markdown test plan (NOT part of the installable Skill folder). */
export function buildTestPlan(content: SkillContent, liveTests: LiveTest[]): string {
  const lines: string[] = [];
  lines.push(`# Live test plan - ${content.name || '(unnamed skill)'}`, '');
  lines.push('Generated by Claude Forge. These are the steps for a MANUAL test in your own Claude Code session. Forge cannot run Claude, so nothing below has been observed yet.', '');
  lines.push('## Setup', '');
  lines.push(`1. Copy the exported \`${content.name || '<skill-name>'}/\` folder into \`~/.claude/skills/\` (personal) or \`.claude/skills/\` (project).`);
  lines.push('2. Start a NEW Claude Code session in the project and run `/skills` to confirm the Skill is listed. (`/reload-skills` is only needed for a newly created top-level skills directory.)');
  lines.push('3. If the Skill does not appear, run `claude --debug` and search for parse or name errors, or run `claude plugin validate <skills-dir>`.', '');
  lines.push('## Scenarios', '');
  lines.push('For each prompt: type it in a fresh conversation, then check the transcript for a Skill tool call naming this Skill. Record what actually happened.', '');
  lines.push('| # | Prompt | Author expects | Observed (fill in) |', '|---|--------|----------------|--------------------|');
  content.scenarios.forEach((s, i) => lines.push(`| ${i + 1} | ${s.prompt.replace(/\|/g, '\\|').replace(/\n/g, ' ')} | ${s.expected} |  |`));
  lines.push('', '## Direct invocation check', '');
  lines.push(`Type \`/${content.name || '<skill-name>'}\` ${content.invocation === 'auto-only' ? '(expected NOT to work: user-invocable is false)' : '(expected to work)'} and confirm the instructions load.`, '');
  if (liveTests.length) {
    lines.push('## Observations already recorded in Forge', '');
    for (const t of liveTests) lines.push(`- ${t.testedAt.slice(0, 10)} - "${t.prompt}" - observed: **${t.observed}**${t.claudeCodeVersion ? ` (Claude Code ${t.claudeCodeVersion})` : ''}${t.notes ? ` - ${t.notes}` : ''}`);
    lines.push('', '_These are your own notes entered in Forge, not independently verified._');
  }
  return lines.join('\n') + '\n';
}
